"""Deploying a compiled project to Amazon Bedrock AgentCore Runtime.

A deployment is AgentCore's "direct code" path: a .zip with the platform package, the
project's validated plan (plan.json), a generated main.py that serves runtime_app, and
every dependency built for Linux arm64 (AgentCore runs nothing else). The zip goes to S3
and becomes one AgentCore runtime per project. No Docker image or registry is involved.

The steps run in a background job and record progress on the project's `deployment`, so
the API returns immediately and the console polls. AWS calls go through AgentCoreCloud
(agentcore.py), which tests replace with a fake.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import shutil
import stat
import subprocess
import tempfile
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Protocol

from .agent_schema import AgentPlan, EmbeddingConfig
from .agentcore import RUNTIME_NAME_PREFIX
from .config import PROVIDER_ENV_VARS
from .errors import DeployError, MissingProviderKeyError, MissingToolKeyError
from .knowledge import SNAPSHOT_FILE, SNAPSHOT_VECTORS_FILE
from .tools import TOOL_ENV_VARS, uses_knowledge

logger = logging.getLogger(__name__)

BACKEND_DIR = Path(__file__).resolve().parents[2]
PACKAGE_DIR = Path(__file__).resolve().parent
CACHE_DIR = BACKEND_DIR / ".deploy-cache"

RUNTIME_PYTHON_VERSION = "3.11"
# AgentCore's direct-code runtime is Amazon Linux 2023 on arm64 (glibc 2.34, as measured
# in AWS's sample-agentcore-launchpad), so manylinux_2_28 wheels run there. The older
# manylinux2014 target in AWS's docs can't resolve packages such as numpy (needed by the
# yahoo_finance_news tool) that no longer publish manylinux2014 arm64 wheels.
RUNTIME_PLATFORM = "aarch64-manylinux_2_28"
# The deployed runtime only serves a plan: it never touches accounts, the database or AWS
# itself. These platform-only packages (and their own dependencies) stay out of the
# bundle — which also matters because not all of them ship Linux arm64 wheels.
PLATFORM_ONLY_PACKAGES = (
    "argon2-cffi",
    "pyjwt",
    "email-validator",
    "pymongo",
    "boto3",
    # Documents are parsed on the platform; a runtime only searches the snapshot.
    "pypdf",
    "python-docx",
    "python-multipart",
)
PLATFORM_ONLY_MODULES = {"app.py", "auth.py", "stores.py", "agentcore.py", "deploy.py"}
# AgentCore's limits for a direct-code package.
MAX_ZIPPED_BYTES = 250 * 1024 * 1024
MAX_UNZIPPED_BYTES = 750 * 1024 * 1024

MAIN_PY = '''"""AgentCore Runtime entry point, generated by the Agentic Platform deploy step."""
import json
import pathlib

import uvicorn

from agentic_platform.runtime_app import create_app

HERE = pathlib.Path(__file__).parent
PLAN = json.loads((HERE / "plan.json").read_text(encoding="utf-8"))
app = create_app(PLAN, knowledge_dir=HERE)

if __name__ == "__main__":
    uvicorn.run(app, host="0.0.0.0", port=8080)
'''


# ------------------------------------------------------------------ naming / environment
def runtime_name(project_id: str) -> str:
    return f"{RUNTIME_NAME_PREFIX}{project_id}"


def runtime_environment(plan: AgentPlan, embedding: EmbeddingConfig | None = None) -> dict[str, str]:
    """The environment variables a deployed plan needs, and nothing else: one key per
    provider its agents use (and for the knowledge base's embedding model, when an agent
    searches it), plus keys for the tools they use. Raises if one is missing here, so a
    deployment never starts that could only fail at run time."""
    env: dict[str, str] = {}
    providers = {agent.llm.provider for agent in plan.agents}
    if embedding is not None and uses_knowledge(plan):
        providers.add(embedding.provider)
    for provider in sorted(providers):
        if provider == "ollama":
            raise DeployError("ollama models run on your own machine and can't be deployed")
        names = PROVIDER_ENV_VARS[provider]
        found = next((n for n in names if os.environ.get(n)), None)
        if found is None:
            raise MissingProviderKeyError(provider, " or ".join(names))
        env[found] = os.environ[found]
    for tool in sorted({t for agent in plan.agents for t in agent.tools}):
        required, optional = TOOL_ENV_VARS.get(tool, ((), ()))
        for name in required:
            if not os.environ.get(name):
                raise MissingToolKeyError(tool, name)
            env[name] = os.environ[name]
        for name in optional:
            if os.environ.get(name):
                env[name] = os.environ[name]
    return env


# ------------------------------------------------------------------ packaging
def _run(cmd: list[str], cwd: Path) -> str:
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        raise DeployError(f"`{' '.join(cmd[:3])} ...` failed: {result.stderr.strip()[-1500:]}")
    return result.stdout


def runtime_requirements() -> str:
    """The backend's locked runtime dependencies, so a deployment runs exactly the
    versions the platform was tested with — minus the platform-only ones."""
    prune = [arg for pkg in PLATFORM_ONLY_PACKAGES for arg in ("--prune", pkg)]
    return _run(
        ["uv", "export", "--frozen", "--no-dev", "--no-emit-project", "--no-hashes", "--no-header", *prune],
        BACKEND_DIR,
    )


def build_dependencies(requirements: str) -> Path:
    """Install the requirements as Linux arm64 wheels into a cached folder (built once
    per distinct lock, then reused)."""
    digest = hashlib.sha256(
        f"{RUNTIME_PLATFORM}|{RUNTIME_PYTHON_VERSION}|{requirements}".encode()
    ).hexdigest()[:16]
    target = CACHE_DIR / f"deps-{digest}"
    if target.is_dir():
        return target
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(dir=CACHE_DIR, prefix="building-"))
    try:
        reqs = staging / "requirements.txt"
        reqs.write_text(requirements, encoding="utf-8")
        _run(
            [
                "uv", "pip", "install",
                "--python-platform", RUNTIME_PLATFORM,
                "--python-version", RUNTIME_PYTHON_VERSION,
                "--only-binary", ":all:",
                "--target", str(staging / "site"),
                "-r", str(reqs),
            ],
            BACKEND_DIR,
        )
        (staging / "site").rename(target)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return target


def _skip(path: Path) -> bool:
    return "__pycache__" in path.parts or path.suffix == ".pyc"


def _add_file(zf: zipfile.ZipFile, arcname: str, data: bytes) -> None:
    info = zipfile.ZipInfo(arcname, date_time=(2026, 1, 1, 0, 0, 0))
    # Built on any OS, read on Linux: mark entries as Unix files with 0644 permissions,
    # which AgentCore requires (a Windows-made zip would otherwise carry none).
    info.create_system = 3
    info.external_attr = (stat.S_IFREG | 0o644) << 16
    info.compress_type = zipfile.ZIP_DEFLATED
    zf.writestr(info, data)


def _dependencies_zip(deps_dir: Path) -> Path:
    """A zip of just the dependencies, cached next to them; each deployment copies it and
    appends its own code, which is far faster than re-compressing hundreds of MB."""
    zipped = deps_dir.with_suffix(".zip")
    if zipped.is_file():
        return zipped
    partial = zipped.with_suffix(".partial")
    with zipfile.ZipFile(partial, "w") as zf:
        for path in sorted(deps_dir.rglob("*")):
            if path.is_file() and not _skip(path):
                _add_file(zf, path.relative_to(deps_dir).as_posix(), path.read_bytes())
    partial.replace(zipped)
    return zipped


def build_package(
    plan: AgentPlan,
    out_path: Path,
    dependencies: Callable[[], Path] | None = None,
    knowledge: tuple[bytes, bytes] | None = None,
) -> dict[str, int]:
    """Write the deployment zip for `plan` to `out_path`; returns its sizes in bytes.
    `knowledge` is the knowledge-base snapshot (knowledge.build_snapshot), if any."""
    deps_dir = dependencies() if dependencies else build_dependencies(runtime_requirements())
    shutil.copyfile(_dependencies_zip(deps_dir), out_path)
    with zipfile.ZipFile(out_path, "a") as zf:
        for path in sorted(PACKAGE_DIR.rglob("*.py")):
            if not _skip(path) and path.name not in PLATFORM_ONLY_MODULES:
                arcname = f"agentic_platform/{path.relative_to(PACKAGE_DIR).as_posix()}"
                _add_file(zf, arcname, path.read_bytes())
        _add_file(zf, "plan.json", json.dumps(plan.model_dump(), indent=2).encode("utf-8"))
        _add_file(zf, "main.py", MAIN_PY.encode("utf-8"))
        if knowledge is not None:
            _add_file(zf, SNAPSHOT_FILE, knowledge[0])
            _add_file(zf, SNAPSHOT_VECTORS_FILE, knowledge[1])
        unzipped = sum(i.file_size for i in zf.infolist())
    zipped = out_path.stat().st_size
    if zipped > MAX_ZIPPED_BYTES or unzipped > MAX_UNZIPPED_BYTES:
        raise DeployError(
            f"deployment package is {zipped // 2**20} MB zipped / {unzipped // 2**20} MB "
            "unzipped; AgentCore allows 250 MB / 750 MB"
        )
    return {"zipped": zipped, "unzipped": unzipped}


# ------------------------------------------------------------------ orchestration
class Cloud(Protocol):
    region: str

    def ensure_bucket(self) -> None: ...
    def upload(self, path: str, key: str) -> None: ...
    def ensure_role(self) -> str: ...
    def deploy_runtime(
        self, name: str, code_key: str, environment: dict[str, str], role_arn: str,
        existing_runtime_id: str | None = None, description: str = "",
    ) -> tuple[str, str]: ...
    def wait_until_ready(self, runtime_id: str) -> None: ...
    def delete_runtime(self, runtime_id: str) -> None: ...
    def delete_code(self, prefix: str) -> None: ...
    def invoke(self, runtime_arn: str, payload: dict[str, Any]) -> dict[str, Any]: ...


Packager = Callable[..., Any]  # (plan, out_path, knowledge=...) -> sizes


def _describe(error: Exception) -> str:
    # Type and message only — never environment values, which can hold keys.
    text = str(error).strip() or "no details"
    return f"{type(error).__name__}: {text}"[:1000]


def run_deployment(
    project_id: str,
    store: Any,
    cloud: Cloud,
    packager: Packager = build_package,
    knowledge_snapshot: Callable[[], tuple[bytes, bytes] | None] | None = None,
    knowledge_embedding: EmbeddingConfig | None = None,
) -> None:
    """The background job: package, upload, provision, wait. Progress and the outcome are
    written to the project's deployment record; this never raises. `knowledge_snapshot`
    supplies the knowledge base to bake in when an agent searches it, embedded with
    `knowledge_embedding` (the owner's library model)."""
    from .stores import Deployment  # local import: stores imports nothing from here

    def update(**changes: Any) -> Deployment | None:
        project = store.get(project_id)
        if project is None or project.deployment is None:
            return None
        deployment = project.deployment.model_copy(
            update={**changes, "updated_at": datetime.now(timezone.utc)}
        )
        store.set_deployment(project_id, deployment)
        return deployment

    project = store.get(project_id)
    if project is None or project.deployment is None:
        return
    current: Deployment = project.deployment
    try:
        environment = runtime_environment(project.plan, knowledge_embedding)
        snapshot = knowledge_snapshot() if knowledge_snapshot is not None else None
        with tempfile.TemporaryDirectory(prefix="agentic-deploy-") as tmp:
            package = Path(tmp) / "package.zip"
            if snapshot is not None:
                packager(project.plan, package, knowledge=snapshot)
            else:
                packager(project.plan, package)

            update(status="uploading")
            cloud.ensure_bucket()
            stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
            key = f"{current.runtime_name}/v{current.plan_version}-{stamp}.zip"
            cloud.upload(str(package), key)

        update(status="provisioning")
        role_arn = cloud.ensure_role()
        runtime_id, runtime_arn = cloud.deploy_runtime(
            current.runtime_name,
            key,
            environment,
            role_arn,
            existing_runtime_id=current.runtime_id,
            description=f"Agentic Platform project {project_id}, plan v{current.plan_version}",
        )
        update(runtime_id=runtime_id, runtime_arn=runtime_arn)
        cloud.wait_until_ready(runtime_id)
        update(
            status="ready",
            error=None,
            live_plan_version=current.plan_version,
            deployed_at=datetime.now(timezone.utc),
        )
    except Exception as e:  # noqa: BLE001 — a background job must record, not raise
        logger.exception("deployment of project %s failed", project_id)
        update(status="failed", error=_describe(e))


def remove_deployment(project_id: str, store: Any, cloud: Cloud) -> None:
    project = store.get(project_id)
    if project is None or project.deployment is None:
        return
    deployment = project.deployment
    if deployment.runtime_id:
        cloud.delete_runtime(deployment.runtime_id)
    cloud.delete_code(f"{deployment.runtime_name}/")
    store.set_deployment(project_id, None)
